"""FastAPI assembler + uvicorn launcher for the viewer (BT-007 split).

Carved out of the pre-split 568-line ``chessboard_viewer.py``. The
module exposes :

* :func:`build_app` — construct the ``FastAPI`` instance, mount the
  domain routers (``games`` / ``positions`` / ``realtime`` / ``elo``)
  and register the index + health root routes.
* :func:`_uvicorn_kwargs` — pure env-var → kwargs mapping, kept
  separate so the unit test can assert the resulting dict without
  booting a server.
* :func:`main` — CLI entry-point ``palamede-chessboard-viewer``.
"""

from __future__ import annotations

import hashlib
import logging
import os

from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import Response
from fastapi.templating import Jinja2Templates

from palamede_chessboard.chessboard_engine import DEFAULT_DEPTH
from palamede_chessboard.viewer.models import (
    CHESSGROUND_DIR,
    CHESSGROUND_VERSION,
    DEPTH_OPTIONS,
    TEMPLATES_DIR,
    VIEWER_ROLES,
)
from palamede_chessboard.viewer.routers import (
    build_elo_router,
    build_games_router,
    build_players_router,
    build_positions_router,
    build_realtime_router,
)

log = logging.getLogger(__name__)

#: Entry templates of the page's scripts, served under /assets/ (#59).
ASSET_TEMPLATES = ("viewer.js", "board.js")

#: Content-Security-Policy of the page (#59) : the page holds the player
#: token, so scripts and requests are limited to the viewer's own origin.
#: ``style-src 'unsafe-inline'`` : the page keeps its <style> block and
#: style="" attributes (generated by the JS too) ; CSS cannot run code.
#: ``img-src data:`` : chessground's pieces are SVG data URIs in its CSS.
CONTENT_SECURITY_POLICY = "; ".join(
    [
        "default-src 'none'",
        "script-src 'self'",
        "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data:",
        "connect-src 'self'",
        "base-uri 'none'",
        "form-action 'none'",
        "frame-ancestors 'none'",
    ]
)


IMMUTABLE = "public, max-age=31536000, immutable"


def _render_assets(templates: Jinja2Templates) -> tuple[dict[str, str], dict[str, bytes]]:
    """Render the page's scripts once (#59 CSP : no inline script).

    Returns the URL of each entry template (for the page) and the content
    of each served file. The content hash in the file name makes the URL
    immutable : a new release yields new URLs.
    """
    urls: dict[str, str] = {}
    files: dict[str, bytes] = {}
    for name in ASSET_TEMPLATES:
        content = (
            templates.env.get_template(f"{name}.jinja")
            .render(chessground_version=CHESSGROUND_VERSION)
            .encode()
        )
        stem, ext = name.rsplit(".", 1)
        filename = f"{stem}.{hashlib.sha256(content).hexdigest()[:12]}.{ext}"
        urls[name] = f"/assets/{filename}"
        files[filename] = content
    return urls, files


def _serve_files(app: FastAPI, prefix: str, files: dict[str, tuple[bytes, str]]) -> None:
    """``GET {prefix}/{name}`` over a closed list of in-memory files, else 404."""

    @app.get(f"{prefix}/{{name}}", include_in_schema=False)
    def static_file(name: str) -> Response:
        if name not in files:
            raise HTTPException(status_code=404)
        content, media_type = files[name]
        return Response(content, media_type=media_type, headers={"Cache-Control": IMMUTABLE})


def build_app() -> FastAPI:
    """Return a freshly-instantiated FastAPI viewer app (test-friendly).

    The function stays an assembler : it only wires the per-domain
    ``APIRouter`` factories under the FastAPI root (so the URL
    contract from the pre-split monolith is preserved byte-for-byte)
    and registers the root routes (``/`` index + ``/api/health``) that
    depend on the ``Jinja2Templates`` instance owned here, plus the
    favicon (a knight on a two-tone square, ``templates/viewer/favicon.svg``)
    and the static scripts and styles of the page (#59).
    """
    app = FastAPI(title="Chess ChessBoard Viewer", version="2.0-phase-c")
    templates = Jinja2Templates(directory=str(TEMPLATES_DIR))
    assets, asset_files = _render_assets(templates)

    @app.get("/")
    def index(request: Request) -> Response:
        response = templates.TemplateResponse(
            request,
            "chessboard_viewer.html.jinja",
            {
                "viewer_roles": VIEWER_ROLES,
                "depth_options": DEPTH_OPTIONS,
                "default_depth": DEFAULT_DEPTH,
                "chessground_version": CHESSGROUND_VERSION,
                "assets": assets,
            },
        )
        response.headers["Content-Security-Policy"] = CONTENT_SECURITY_POLICY
        return response

    @app.get("/api/health")
    def health() -> dict:
        return {"status": "ok"}

    favicon = (TEMPLATES_DIR / "viewer" / "favicon.svg").read_bytes()

    # /favicon.ico : browsers ask for it without reading the page ; SVG
    # is served there too, every current browser accepts it.
    @app.get("/favicon.svg", include_in_schema=False)
    @app.get("/favicon.ico", include_in_schema=False)
    def favicon_svg() -> Response:
        return Response(
            favicon,
            media_type="image/svg+xml",
            headers={"Cache-Control": "public, max-age=86400"},
        )

    _serve_files(app, "/assets", {n: (c, "text/javascript") for n, c in asset_files.items()})

    # chessground, embedded in the package (issue #59) : the page holds the
    # player token, so no script may come from a third-party origin. Fixed
    # list of files read at build time, versioned URL, hence immutable.
    vendor_types = {".js": "text/javascript", ".css": "text/css"}
    vendor = {
        f.name: (f.read_bytes(), vendor_types[f.suffix])
        for f in CHESSGROUND_DIR.iterdir()
        if f.suffix in vendor_types
    }
    _serve_files(app, f"/vendor/chessground@{CHESSGROUND_VERSION}", vendor)

    app.include_router(build_games_router())
    app.include_router(build_positions_router())
    app.include_router(build_realtime_router())
    app.include_router(build_elo_router())
    app.include_router(build_players_router())
    return app


app = build_app()


def _uvicorn_kwargs() -> dict:
    """Build the ``uvicorn.run`` kwargs from env vars (test-friendly).

    Environment variables read :

    * ``MCP_CHESSBOARD_VIEWER_HOST`` (default ``127.0.0.1``).
    * ``MCP_CHESSBOARD_VIEWER_PORT`` (default ``8765``).
    * ``MCP_CHESSBOARD_VIEWER_FORWARDED_IPS`` (default ``127.0.0.1``) :
      liste d'IPs reverse proxy autorisées à pousser ``X-Forwarded-*``.
      Mettre ``*`` pour faire confiance à n'importe quel proxy
      (acceptable en LAN privé fermé), ou lister explicitement les IPs
      reverse proxy (ex. ``192.168.1.78`` pour DSM).
    """
    return {
        "app": "palamede_chessboard.viewer.app:app",
        "host": os.environ.get("MCP_CHESSBOARD_VIEWER_HOST", "127.0.0.1"),
        "port": int(os.environ.get("MCP_CHESSBOARD_VIEWER_PORT", "8765")),
        "reload": False,
        "proxy_headers": True,
        "forwarded_allow_ips": os.environ.get("MCP_CHESSBOARD_VIEWER_FORWARDED_IPS", "127.0.0.1"),
    }


def main() -> None:
    """CLI entry point ``palamede-chessboard-viewer`` (uvicorn launcher).

    Quand le viewer tourne derrière un reverse proxy (ex. DSM
    ``*.alliancejr.eu``), ``proxy_headers=True`` permet à uvicorn de
    lire ``X-Forwarded-Proto`` / ``X-Forwarded-For`` /
    ``X-Forwarded-Host`` et de loguer le vrai client IP au lieu de
    l'IP du proxy.
    """
    import uvicorn

    uvicorn.run(**_uvicorn_kwargs())


if __name__ == "__main__":
    main()
